"""Build Onward/Places.lua: the named areas of each zone map, so a spot can be called by name
("Powderfuse Port, Riverglades 83, 52" instead of just the coordinates).

    python tools/make_places.py            # uses the cached tables
    python tools/make_places.py --fetch    # downloads them first

Source: Forever's own client tables, exported by wago.tools (same build as the profession data):
the world map's exploration overlays (WorldMapOverlay: an area and its hit rectangle on the map
art), which map art each zone uses (UiMapXMapArt), and the area names (AreaTable). Those are the
regions the game itself names when you hover the world map. The art is 1002 x 668 pixels; the
rectangles are stored here in the 0-100 map coordinates the addon uses.
"""
import csv
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUILD = "1.60.1.70938"
DATA = ROOT / "tools" / "data" / "db2" / BUILD
OUT = ROOT / "Onward" / "Places.lua"
TABLES = ["WorldMapOverlay", "UiMapXMapArt", "AreaTable"]
ART_W, ART_H = 1002, 668


def fetch():
    DATA.mkdir(parents=True, exist_ok=True)
    for t in TABLES:
        url = f"https://wago.tools/db2/{t}/csv?build={BUILD}"
        print("fetch", url)
        req = urllib.request.Request(url, headers={"User-Agent": "onward-tools"})
        with urllib.request.urlopen(req, timeout=300) as r:
            (DATA / f"{t}.csv").write_bytes(r.read())


def rows(t):
    with open(DATA / f"{t}.csv", encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def main():
    if "--fetch" in sys.argv or not all((DATA / f"{t}.csv").exists() for t in TABLES):
        fetch()
    names = {int(r["ID"]): r["AreaName_lang"] for r in rows("AreaTable")}
    art_maps = {}
    for r in rows("UiMapXMapArt"):
        art_maps.setdefault(int(r["UiMapArtID"]), set()).add(int(r["UiMapID"]))
    by_map = {}
    for r in rows("WorldMapOverlay"):
        area = next((int(r[f"AreaID_{i}"]) for i in range(4) if int(r[f"AreaID_{i}"])), 0)
        name = names.get(area)
        if not name:
            continue
        l, t = float(r["HitRectLeft"]) / ART_W * 100, float(r["HitRectTop"]) / ART_H * 100
        rr, b = float(r["HitRectRight"]) / ART_W * 100, float(r["HitRectBottom"]) / ART_H * 100
        if rr <= l or b <= t:
            continue
        for m in art_maps.get(int(r["UiMapArtID"]), ()):
            by_map.setdefault(m, set()).add((round(l, 1), round(t, 1), round(rr, 1), round(b, 1), name))
    out = ["-- GENERATED by tools/make_places.py from Forever's client tables (wago.tools export, build "
           f"{BUILD}):", "-- the world map's named areas per zone, as { left, top, right, bottom, name } in 0-100 map units.",
           "local _, W = ...", "W.PlaceData = {"]
    for m in sorted(by_map):
        out.append(f"  [{m}] = {{")
        for l, t, rr, b, name in sorted(by_map[m]):
            out.append(f'    {{ {l}, {t}, {rr}, {b}, "{name.replace(chr(34), "")}" }},')
        out.append("  },")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(by_map)} maps, {sum(len(v) for v in by_map.values())} named areas")


if __name__ == "__main__":
    main()
