"""Write Onward/Guides/QuestSpots.lua from tools/quest_spots.json.

    python tools/make_spots.py

quest_spots.json holds objective locations for quests Questie has no spawn data for, looked up
one quest at a time (see its _about). The addon uses them like Questie's spawns: the arrow goes
to the nearest spot of an unfinished objective. draft_guide.py reads the JSON directly.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "quest_spots.json"
OUT = ROOT / "Onward" / "Guides" / "QuestSpots.lua"


def load():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    return {int(q): v for q, v in data.items() if not q.startswith("_")}


def main():
    spots = load()
    out = ["-- GENERATED by tools/make_spots.py from tools/quest_spots.json: objective spots for quests",
           "-- Questie has no spawn data for. [questId] = { { map, \"objective item\", \"x,y x,y ...\" }, ... }",
           "local _, W = ...", "W.QuestSpots = {"]
    for q in sorted(spots):
        out.append(f"  [{q}] = {{")
        for e in spots[q]:
            what = e["what"].replace('"', "")
            out.append(f'    {{ {e["map"]}, "{what}", "{e["points"]}" }},')
        out.append("  },")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(spots)} quests")


if __name__ == "__main__":
    main()
